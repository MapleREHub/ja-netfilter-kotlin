/*
 * ============================================================================
 * - Ruler.kt - 规则匹配器接口
 * ----------------------------------------------------------------------------
 * 用于判断一个字符串是否符合某个规则。
 *
 * 所有具体的匹配器都实现该接口，并通过 RuleType 枚举进行绑定。
 * 这是策略模式（Strategy Pattern）的典型应用。
 * ============================================================================
 */
package com.janetfilter.core.rulers

/**
 * 规则匹配器接口
 *
 * 每个具体实现提供一种字符串匹配策略。
 */
fun interface Ruler {
    /**
     * 判断输入是否符合规则
     *
     * @param rule 规则字符串
     * @param input 输入字符串
     * @return true 表示匹配，false 表示不匹配
     */
    fun test(rule: String, input: String): Boolean
}